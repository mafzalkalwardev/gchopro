fun deliveryEvent(status: Int): String = when {
    status == 0 -> "delivered"
    status >= 64 -> "delivery_failed"
    status in 32..63 -> "delivery_pending"
    else -> "delivery_failed"
}

fun localRefusal(active: Boolean): String? = if (active) null else "LOCAL_SUBSCRIPTION_NOT_ACTIVE"
