export type ScreenId = keyof typeof en;

const catalogs = new Map<Locale, Map<string, string>>([
  ["en", new Map(Object.entries(en))],
  ["zh-CN", new Map(Object.entries(zh))],
]);

export function asLocale(value: string | undefined): Locale {
  return value === "zh-CN" ? "zh-CN" : "en";
}

export function screenCopy(locale: string, id: ScreenId): string {
  const chosen = catalogs.get(asLocale(locale)) ?? catalogs.get("en");
  return chosen?.get(id) ?? catalogs.get("en")?.get(id) ?? id;
}

export function catalogKeys(): ScreenId[] {
  return [...(catalogs.get("en")?.keys() ?? [])] as ScreenId[];
}
