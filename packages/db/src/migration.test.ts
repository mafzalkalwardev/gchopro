import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

describe("first migration", () => {
  const sql = readFileSync(
    resolve(dirname(fileURLToPath(import.meta.url)), "../migrations/0000_pink_morph.sql"),
    "utf8",
  );

  it("creates citext before the users table", () => {
    const extension = sql.indexOf("CREATE EXTENSION IF NOT EXISTS citext");
    const users = sql.indexOf('CREATE TABLE "users"');
    expect(extension).toBeGreaterThanOrEqual(0);
    expect(users).toBeGreaterThan(extension);
  });

  it("keeps the audit log append-only identity and the partial uniques", () => {
    expect(sql).toContain('CREATE TABLE "audit_logs"');
    expect(sql).toContain("GENERATED BY DEFAULT AS IDENTITY");
    expect(sql).toContain("opt_outs_active_unique");
    expect(sql).toContain("messages_device_provider");
    expect(sql).toContain("stats_daily_day_sim_id_user_scope_id_pk");
    expect(sql).toContain("subscriptions_one_open");
  });
});
